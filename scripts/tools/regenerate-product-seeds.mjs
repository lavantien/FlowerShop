import {readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const PRODUCT_JSON = path.join(REPO_ROOT, 'db/product.json');
const SEED_SQL = path.join(REPO_ROOT, 'db/seed.sql');
const USD_TO_VND = 23000;
const ROUND_TO = 1000;
const STOCK_PER_BRANCH = 25;
const BRANCH_COUNT = 6;
const FIELD_ORDER = ['id', 'categoryName', 'description', 'imgUrl', 'name', 'price', 'typeName'];

const PRODUCT_DDL = `create table if not exists product (
	id bigint not null auto_increment,
	category_name varchar(255) default null,
	description varchar(2000) default null,
	img_url varchar(2000) default null,
	name varchar(255) default null,
	price decimal(12,0) default null,
	type_name varchar(255) default null,
	primary key (id)
) engine=InnoDB default charset=utf8mb4 collate=utf8mb4_0900_ai_ci;`;

const STOCK_DDL = `create table if not exists stock_level (
	id bigint not null auto_increment,
	branch_id bigint default null,
	product_id bigint default null,
	quantity int not null,
	primary key (id),
	unique key UKo3w3fq3nqjlhy6k7gq1ooemlb (branch_id, product_id)
) engine=InnoDB default charset=utf8mb4 collate=utf8mb4_0900_ai_ci;`;

function toVnd(usd) {
	const cents = Math.round(usd * 100);
	return Math.round(cents * USD_TO_VND / 100 / ROUND_TO) * ROUND_TO;
}

function sqlString(value) {
	if (/[\r\n\t]/.test(value)) {
		throw new Error(`control character in seed string: ${JSON.stringify(value.slice(0, 80))}`);
	}
	return `'${value.replace(/'/g, "''")}'`;
}

function convert(product) {
	if (/^https?:\/\//i.test(product.imgUrl)) {
		return product;
	}
	const decoded = Buffer.from(product.imgUrl, 'base64').toString('utf8');
	if (!/^https?:\/\//i.test(decoded)) {
		throw new Error(`product ${product.id}: imgUrl does not decode to a URL`);
	}
	return {...product, imgUrl: decoded, price: toVnd(product.price)};
}

function normalize(product) {
	for (const field of FIELD_ORDER) {
		if (product[field] === undefined) {
			throw new Error(`product ${product.id ?? '?'}: missing field ${field}`);
		}
	}
	return Object.fromEntries(FIELD_ORDER.map(field => [field, product[field]]));
}

function productStatement(product) {
	const columns = ['name', 'description', 'img_url', 'price', 'type_name', 'category_name'];
	const values = [
		sqlString(product.name),
		sqlString(product.description),
		sqlString(product.imgUrl),
		product.price,
		sqlString(product.typeName),
		sqlString(product.categoryName)
	].join(', ');
	const updates = columns.map(column => `${column} = v.${column}`).join(', ');
	return `insert into product (id, ${columns.join(', ')}) values (${product.id}, ${values}) as v\non duplicate key update ${updates};`;
}

function stockStatement(branchId, products) {
	const rows = products
		.map(product => `\t(${branchId}, ${product.id}, ${STOCK_PER_BRANCH})`)
		.join(',\n');
	return `insert into stock_level (branch_id, product_id, quantity) values\n${rows} as v\non duplicate key update quantity = v.quantity;`;
}

const source = JSON.parse(await readFile(PRODUCT_JSON, 'utf8'));
const products = source.map(convert).map(normalize).sort((a, b) => a.id - b.id);

await writeFile(PRODUCT_JSON, `${JSON.stringify(products, null, '\t')}\n`, 'utf8');

const lines = [
	'-- Generated by scripts/tools/regenerate-product-seeds.mjs, do not edit.',
	'-- Regenerate with: make seeds',
	'',
	PRODUCT_DDL,
	'',
	STOCK_DDL,
	''
];
for (const product of products) {
	lines.push('', productStatement(product));
}
for (let branchId = 1; branchId <= BRANCH_COUNT; branchId++) {
	lines.push('', stockStatement(branchId, products));
}
await writeFile(SEED_SQL, `${lines.join('\n')}\n`, 'utf8');

console.log(`products: ${products.length}`);
console.log(`stock rows: ${products.length * BRANCH_COUNT} (${STOCK_PER_BRANCH} x ${BRANCH_COUNT} branches)`);
